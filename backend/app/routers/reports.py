router = APIRouter(prefix="/api", tags=["reports"])


def filters(date_from: datetime | None = None, date_to: datetime | None = None, project_id: int | None = None,
            client_id: int | None = None, severity: str | None = Query(None, pattern="^(critical|major|minor|info)$"),
            data: str = Query("all", pattern="^(all|real|sample)$"), editor_id: int | None = None) -> metrics.Filters:
    return metrics.Filters(date_from, date_to, project_id, client_id, severity, data, editor_id)


@router.get("/dashboard")
def get_dashboard(f: metrics.Filters = Depends(filters), user: User = Depends(needs("dashboard.view")), db: Session = Depends(get_db)):
    return metrics.dashboard(db, user, f)


@router.get("/reports")
def catalog(user: User = Depends(needs("reports.view"))):
    return [{"key": k, "title": t} for k, t in metrics.REPORTS.items() if Role(user.role) in REPORT_ACCESS[k]]


def _check(name: str, user: User) -> None:
    if name not in metrics.REPORTS:
        raise HTTPException(404, "Unknown report.")
    if Role(user.role) not in REPORT_ACCESS[name]:
        raise HTTPException(403, "Your role cannot open this report.")


@router.get("/reports/{name}")
def get_report(name: str, f: metrics.Filters = Depends(filters), user: User = Depends(needs("reports.view")), db: Session = Depends(get_db)):
    _check(name, user)
    return metrics.build_report(db, user, name, f)


def _safe(v):
    if isinstance(v, str) and v[:1] in ("=", "+", "-", "@", "\t", "\r"):
        return "'" + v  # neutralise spreadsheet formula injection
    return v


@router.get("/reports/{name}/export")
def export(name: str, request: Request, fmt: str = Query("csv", pattern="^(csv|xlsx)$"), f: metrics.Filters = Depends(filters),
           user: User = Depends(needs("reports.export")), db: Session = Depends(get_db)):
    _check(name, user)
    rep = metrics.build_report(db, user, name, f)
    cols, rows = rep["columns"], rep["rows"]
    db.add(ExportJob(user_id=user.id, report=name, fmt=fmt, filters=f.as_dict(), row_count=len(rows)))
    audit(db, user, "report.exported", entity_type="report", entity_id=name, detail={"fmt": fmt, "rows": len(rows), "filters": f.as_dict()}, request=request)
    db.commit()
    stamp = datetime.utcnow().strftime("%Y%m%d-%H%M")
    if fmt == "csv":
        buf = io.StringIO()
        w = csv.writer(buf)
        w.writerow(cols)
        for r in rows:
            w.writerow([_safe(r.get(c)) for c in cols])
        return Response(buf.getvalue().encode("utf-8-sig"), media_type="text/csv",
                        headers={"Content-Disposition": f'attachment; filename="{name}-{stamp}.csv"'})
    wb = Workbook()
    ws = wb.active
    ws.title = "Report"
    ws.append(cols)
    for c in ws[1]:
        c.font = Font(bold=True)
    for r in rows:
        ws.append([_safe(r.get(c)) for c in cols])
    meta = wb.create_sheet("Filters")
    meta.append(["Report", rep["title"]])
    meta.append(["Generated (UTC)", rep["generated_at"]])
    meta.append(["Generated by", user.email])
    meta.append(["Rows", len(rows)])
    for k, v in (rep.get("filters") or {}).items():
        meta.append([k, str(v)])
    out = io.BytesIO()
    wb.save(out)
    return Response(out.getvalue(), media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                    headers={"Content-Disposition": f'attachment; filename="{name}-{stamp}.xlsx"'})


class BatchIn(BaseModel):
    form_ids: list[int] = Field(min_length=1, max_length=100)


@router.post("/reports/qc-batch")
def qc_report_batch(body: BatchIn, request: Request, user: User = Depends(needs("qc.report")), db: Session = Depends(get_db)):
    """ZIP of QC report PDFs for several forms (only forms the caller may see; others are listed in SKIPPED.txt)."""
    forms = db.execute(select(Form).where(Form.id.in_(body.form_ids)).where(form_scope_clause(db, user))).scalars().all()
    if not forms:
        raise HTTPException(404, "None of these forms were found within your access.")
    buf = io.BytesIO()
    skipped = [f"form {i}: not found or not within your access" for i in set(body.form_ids) - {f.id for f in forms}]
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for f in forms:
            try:
                data, name = qc_report.build_report(db, f, user)
                z.writestr(name, data)
            except Exception as exc:  # noqa: BLE001
                skipped.append(f"{f.form_code}: {exc}")
        if skipped:
            z.writestr("SKIPPED.txt", "\n".join(skipped))
    audit(db, user, "report.qc_batch_downloaded", entity_type="report", entity_id="qc-batch", detail={"forms": [f.id for f in forms], "skipped": len(skipped)}, request=request)
    db.commit()
    return Response(buf.getvalue(), media_type="application/zip", headers={"Content-Disposition": f'attachment; filename="QC_Reports_{datetime.utcnow().strftime("%Y%m%d-%H%M")}.zip"'})
